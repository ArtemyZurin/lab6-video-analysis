"""Зафиксировать только зависимости лабораторной, без посторонних пакетов системного Python."""
import importlib.metadata as metadata
import platform
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

from video_lab.common import ROOT, save_json, sha256


def main():
    pending = [Requirement(line).name for line in (ROOT / "requirements.txt").read_text().splitlines()
               if line.strip() and not line.startswith("#")]
    packages = {}
    while pending:
        name = canonicalize_name(pending.pop())
        if name in packages:
            continue
        dist = metadata.distribution(name)
        packages[name] = dist.version
        for declaration in dist.requires or []:
            requirement = Requirement(declaration)
            if requirement.marker is None or requirement.marker.evaluate({"extra": ""}):
                pending.append(requirement.name)
    lines = ["# Python " + platform.python_version() + "; " + platform.system(),
             "# Only the project's dependency closure; generated by freeze_environment.py"]
    lines += [f"{name}=={version}" for name, version in sorted(packages.items())]
    (ROOT / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    save_json(ROOT / "results" / "environment.json", {"python": platform.python_version(),
              "platform": platform.platform(), "packages": packages,
              "models": {p.relative_to(ROOT).as_posix(): sha256(p) for p in (ROOT / "models").rglob("*.pt")}})
    print(f"Pinned {len(packages)} packages")


if __name__ == "__main__":
    main()
